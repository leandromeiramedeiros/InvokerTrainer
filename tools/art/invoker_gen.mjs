// Generates js/art/invoker.js (sheets 'invoker' + 'forge'). Run: node tools/art/invoker_gen.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { G, W, H, PAL, NB } from './invoker_gen_core.mjs';
import { sStamps, nStamps } from './invoker_stamps.mjs';
import { eStamps } from './invoker_stamps_e.mjs';
import { buildForge } from './forge_gen.mjs';
import { orbs, portrait } from './invoker_icons.mjs';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
// ---------- poses ----------
// every pose: { bob, headDy, ... } consumed by each direction's composer (see stamps file)
const ANIMS = {
  idle: 4, walk: 4, cast: 3, attack: 3, stunned: 2,
};
const frames = {};
for (const dir of ['s', 'n', 'e']) {
  const comp = { s: sStamps, n: nStamps, e: eStamps }[dir];
  for (const [anim, n] of Object.entries(ANIMS)) for (let i = 0; i < n; i++) {
    const g = new G();
    comp(g, anim, i);
    // global 1px outline for anything left unoutlined
    const out = g.a.map(r => r.slice());
    for (let y = 0; y < H; y++) for (let x = 0; x < W; x++) if (g.a[y][x] === '.' && NB.some(([dx, dy]) => g.get(x + dx, y + dy) !== '.')) out[y][x] = 'K';
    frames[`${anim}_${dir}_${i}`] = out.map(r => r.join(''));
  }
}
for (const k of ['q', 'w', 'e']) frames['orb_' + k] = orbs[k];
frames.portrait = portrait(frames.idle_s_0);

const forge = buildForge();
const fmt = o => '{\n' + Object.entries(o).map(([k, v]) => `  ${k}: [\n${v.map(r => `    '${r}'`).join(',\n')}\n  ]`).join(',\n') + '\n  }';
const palStr = p => '{ ' + Object.entries(p).map(([k, v]) => `'${k}':'${v}'`).join(', ') + ' }';
const src = `// GENERATED by tools/art/invoker_gen.mjs - edit the generator, not this file.
(function(G){ 'use strict'; const IT = G.IT;
IT.Art.sheet('invoker', {
  pal: ${palStr(PAL)},
  anchor: [13, 27],
  frames: ${fmt(frames)}
});
IT.Art.sheet('forge', {
  pal: ${palStr(forge.pal)},
  anchor: [7, 15],
  frames: ${fmt(forge.frames)}
});
})(typeof window !== 'undefined' ? window : globalThis);
`;
// keep any tail the old file had? (old file ended with the IIFE close)
fs.writeFileSync(path.join(ROOT, 'js/art/invoker.js'), src);
console.log('wrote js/art/invoker.js', Object.keys(frames).length, 'invoker frames,', Object.keys(forge.frames).length, 'forge frames');
