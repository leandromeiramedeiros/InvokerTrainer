// Generates js/art/invoker_skins.js (sheets 'invoker_kid' + 'invoker_dark'). Called by invoker_gen.mjs, or run directly.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildFrames, trimPal, fmt, palStr } from './invoker_build.mjs';
import { PAL_D, compose as dark } from './invoker_dark.mjs';
import { PAL_K, compose as kid } from './invoker_kid.mjs';
import { addCape, PX, PY } from './invoker_cape.mjs';

// cape palettes (chars L J I H G ramp, T trim, R S glow rim, g h halo; see invoker_cape.mjs)
const CAPE_D = { L: '#d9a8ff', J: '#9a5ae0', I: '#6a30b0', H: '#3e1c70', G: '#220e44', T: '#f4d8ff', R: '#ee7aff', S: '#a83ad8', g: '#ee7aff99', h: '#ee7aff44' };
const CAPE_E = { L: '#f6d37a', J: '#d9a043', I: '#a8701f', H: '#6e4512', G: '#3a230a', T: '#ffe9a0', R: '#ff3b2a', S: '#d02418', g: '#ff3b2aaa', h: '#ff3b2a55' };
// Exalted body = the Dark Artistry skeleton re-coloured: black robe, gold trim / horns, silver-white hair (ref 11.png)
const PAL_E = Object.assign({}, PAL_D, {
  P: '#3e3848', Q: '#2a2534', q: '#1a1624', r: '#0f0c18',
  C: '#fff0b0', c: '#ecc050', D: '#b8822a', d: '#6e4812',
  F: '#ffffff', f: '#eceaf6', Y: '#cfcce2', y: '#aeaacb', O: '#8c88ad', E: '#605c82',
  e: '#ff6a3c', z: '#2a1c20',
});

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
export function genSkins() {
  const sheets = {};
  const kFrames = buildFrames(kid, { portraitY: 1 });
  sheets.invoker_kid = { pal: trimPal(PAL_K, kFrames), frames: kFrames };
  const dFrames = buildFrames(dark, { post: dark.mist, pad: (out, q) => addCape(out, { kind: 'cloak', ...q }) });
  sheets.invoker_dark = { pal: trimPal({ ...PAL_D, ...CAPE_D }, dFrames), frames: dFrames, pad: true };
  const eFrames = buildFrames(dark, { pad: (out, q) => addCape(out, { kind: 'wings', ...q }) });
  sheets.invoker_exalted = { pal: trimPal({ ...PAL_E, ...CAPE_E }, eFrames), frames: eFrames, pad: true };
  const src = `// GENERATED by tools/art/invoker_skins_gen.mjs - edit the generator, not this file.
(function(G){ 'use strict'; const IT = G.IT;
${Object.entries(sheets).map(([n, s]) => `IT.Art.sheet('${n}', {
  pal: ${palStr(s.pal)},
  anchor: [${s.pad ? 13 + PX : 13}, ${s.pad ? 27 + PY : 27}],
  frames: ${fmt(s.frames)}
});`).join('\n')}
})(typeof window !== 'undefined' ? window : globalThis);
`;
  fs.writeFileSync(path.join(ROOT, 'js/art/invoker_skins.js'), src);
  console.log('wrote js/art/invoker_skins.js', Object.entries(sheets).map(([n, s]) => n + ':' + Object.keys(s.frames).length).join(' '));
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) genSkins();
